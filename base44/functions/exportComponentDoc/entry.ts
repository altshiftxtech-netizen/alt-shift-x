import { createClientFromRequest } from 'npm:@base44/sdk@0.8.25';
import { jsPDF } from 'npm:jspdf@4.0.0';

Deno.serve(async (req) => {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });

    const { framework, component, format } = await req.json();

    const title = component?.displayName || framework?.framework_name || 'Component Framework';
    const timestamp = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });

    // Build content sections
    const sections = [];

    sections.push({ heading: 'Component Framework Document', sub: `Generated by BOB · ${timestamp} · Alt+Shift+X Platform` });
    sections.push({ heading: 'Project Identity', lines: [
      `Project Name: ${framework?.project?.project_name || '—'}`,
      `Project Code: ${framework?.project?.project_code || '—'}`,
      `Industry: ${framework?.project?.industry_vertical || '—'}`,
      `Target Market: ${framework?.project?.target_market || '—'}`,
      `Platform Type: ${framework?.project?.platform_type || '—'}`,
    ]});
    sections.push({ heading: 'Component Identity', lines: [
      `Type: ${framework?.component_identity?.component_type || component?.type || '—'}`,
      `Category: ${framework?.component_identity?.category || component?.category || '—'}`,
      `Version Scheme: ${framework?.component_identity?.version_scheme || '—'}`,
      `License: ${framework?.component_identity?.license_type || '—'}`,
      `Base Components: ${(framework?.component_identity?.base_components || []).join(', ') || 'None'}`,
    ]});
    sections.push({ heading: 'AI Behavior Configuration', lines: [
      `Model Preference: ${framework?.ai_behavior?.model_preference || '—'}`,
      `Context Window: ${framework?.ai_behavior?.context_window || '—'}`,
      `Extraction Mode: ${framework?.ai_behavior?.extraction_mode || '—'}`,
      `Hallucination Guard: ${framework?.ai_behavior?.hallucination_guard ? 'Enabled' : 'Disabled'}`,
      `Confidence Threshold: ${framework?.ai_behavior?.confidence_threshold || '—'}`,
      `Fallback Behavior: ${framework?.ai_behavior?.fallback_behavior || '—'}`,
    ]});
    sections.push({ heading: 'Input / Output Specification', lines: [
      `Accepted File Types: ${(framework?.input_output?.accepted_file_types || []).join(', ') || '—'}`,
      `Max File Size: ${framework?.input_output?.max_file_size_mb || '—'} MB`,
      `Output Format: ${framework?.input_output?.output_format || '—'}`,
      `Schema Fields: ${(framework?.input_output?.schema_fields || []).join(', ') || '—'}`,
      `Batch Processing: ${framework?.input_output?.supports_batch ? 'Yes' : 'No'}`,
    ]});
    sections.push({ heading: 'Compliance & Safety', lines: [
      `Regulatory Frameworks: ${(framework?.compliance_safety?.regulatory_frameworks || []).join(', ') || '—'}`,
      `Data Residency: ${framework?.compliance_safety?.data_residency || '—'}`,
      `PII Handling: ${framework?.compliance_safety?.pii_handling || '—'}`,
      `Audit Logging: ${framework?.compliance_safety?.audit_logging ? 'Enabled' : 'Disabled'}`,
    ]});
    sections.push({ heading: 'Pricing & Monetization', lines: [
      `Pricing Model: ${framework?.pricing_monetization?.pricing_model || '—'}`,
      `Base Price: $${framework?.pricing_monetization?.base_price || '—'}/mo`,
      `Free Tier Calls: ${framework?.pricing_monetization?.free_tier_calls || 0}`,
      `Trial Days: ${framework?.pricing_monetization?.trial_days || 14}`,
      `Target Margin: ${framework?.pricing_monetization?.target_margin_pct || '—'}%`,
    ]});
    sections.push({ heading: 'Deployment Configuration', lines: [
      `Deploy Target: ${framework?.deployment?.deploy_target || '—'}`,
      `Auto-Publish: ${framework?.deployment?.auto_publish ? 'Yes' : 'No'}`,
      `CI/CD: ${framework?.deployment?.ci_cd_enabled ? 'Enabled' : 'Disabled'}`,
      `Rollback: ${framework?.deployment?.rollback_strategy || '—'}`,
      `Environment: ${framework?.deployment?.environment || '—'}`,
    ]});

    if (format === 'word') {
      // Generate simple HTML for Word download
      let html = `<!DOCTYPE html><html><head><meta charset="utf-8"><style>
        body { font-family: Calibri, Arial, sans-serif; margin: 40px; color: #1e293b; }
        h1 { font-size: 24px; color: #4f46e5; border-bottom: 3px solid #4f46e5; padding-bottom: 8px; }
        h2 { font-size: 16px; color: #334155; margin-top: 28px; border-bottom: 1px solid #e2e8f0; padding-bottom: 4px; }
        p { font-size: 13px; margin: 4px 0; color: #475569; }
        .sub { font-size: 11px; color: #94a3b8; margin-top: -8px; }
        .footer { margin-top: 48px; padding-top: 16px; border-top: 1px solid #e2e8f0; font-size: 10px; color: #94a3b8; }
      </style></head><body>`;

      sections.forEach((s, i) => {
        if (i === 0) {
          html += `<h1>${s.heading}</h1><p class="sub">${s.sub}</p>`;
        } else {
          html += `<h2>${s.heading}</h2>`;
          s.lines.forEach(l => { html += `<p>${l}</p>`; });
        }
      });

      html += `<div class="footer">Generated by BOB (BotOperatedBuilder) · Alt+Shift+X Marketplace · ${timestamp}</div></body></html>`;

      return new Response(html, {
        headers: {
          'Content-Type': 'application/msword',
          'Content-Disposition': `attachment; filename="${title.replace(/\s+/g, '_')}_Framework.doc"`,
        }
      });
    }

    // PDF generation
    const doc = new jsPDF();
    let y = 20;

    // Header
    doc.setFillColor(79, 70, 229);
    doc.rect(0, 0, 210, 40, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.text('Component Framework Document', 15, 18);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.text(`Generated by BOB · ${timestamp} · Alt+Shift+X`, 15, 28);
    doc.text(`Builder: ${user.full_name || user.email}`, 15, 35);
    y = 52;

    sections.slice(1).forEach(section => {
      if (y > 260) { doc.addPage(); y = 20; }

      doc.setFillColor(241, 245, 249);
      doc.rect(10, y - 4, 190, 9, 'F');
      doc.setTextColor(51, 65, 85);
      doc.setFontSize(11);
      doc.setFont('helvetica', 'bold');
      doc.text(section.heading, 14, y + 2);
      y += 12;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      section.lines.forEach(line => {
        if (y > 270) { doc.addPage(); y = 20; }
        doc.text(line, 16, y);
        y += 7;
      });
      y += 4;
    });

    // Footer
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text('BOB (BotOperatedBuilder) · Alt+Shift+X Marketplace · Powered by Magna Dev / Yotta Protocol', 15, 285);

    const pdfBytes = doc.output('arraybuffer');
    return new Response(pdfBytes, {
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="${title.replace(/\s+/g, '_')}_Framework.pdf"`,
      }
    });
  } catch (error) {
    console.error('[exportComponentDoc]', error.message);
    return Response.json({ error: error.message }, { status: 500 });
  }
});