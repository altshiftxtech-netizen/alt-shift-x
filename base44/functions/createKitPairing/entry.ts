import { createClientFromRequest } from 'npm:@base44/sdk@0.8.31';

// SHA-256 hash so the IP statement can't be silently altered after acceptance
async function sha256(text) {
  const data = new TextEncoder().encode(text);
  const digest = await crypto.subtle.digest('SHA-256', data);
  return Array.from(new Uint8Array(digest)).map((b) => b.toString(16).padStart(2, '0')).join('');
}

Deno.serve(async (req) => {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });

    const { requesterComponentId, partnerComponentId, kitName } = await req.json();
    if (!requesterComponentId || !partnerComponentId) {
      return Response.json({ error: 'Both component IDs are required' }, { status: 400 });
    }

    // Load both components (service role so we can read the partner's published component)
    const reqComp = await base44.asServiceRole.entities.Component.filter({ id: requesterComponentId }).then((r) => r[0]);
    const partComp = await base44.asServiceRole.entities.Component.filter({ id: partnerComponentId }).then((r) => r[0]);

    if (!reqComp || !partComp) return Response.json({ error: 'Component not found' }, { status: 404 });

    // Ownership check — requester must own their component
    if (reqComp.builder_id !== user.id) {
      return Response.json({ error: 'You can only pair components you own' }, { status: 403 });
    }
    if (partComp.builder_id === user.id) {
      return Response.json({ error: 'Partner component must belong to a different builder' }, { status: 400 });
    }
    if (partComp.status !== 'published') {
      return Response.json({ error: 'Partner component must be published' }, { status: 400 });
    }

    // Prevent duplicate active requests for the same pair
    const existing = await base44.asServiceRole.entities.KitPairing.filter({
      requester_component_id: requesterComponentId,
      partner_component_id: partnerComponentId,
    });
    if (existing.some((p) => ['pending', 'accepted'].includes(p.status))) {
      return Response.json({ error: 'A pairing request for these components already exists' }, { status: 409 });
    }

    // Proportional revenue split based on list price
    const reqPrice = Number(reqComp.price) || 0;
    const partPrice = Number(partComp.price) || 0;
    const total = reqPrice + partPrice || 1;
    const requesterPct = Math.round((reqPrice / total) * 10000) / 100;
    const partnerPct = Math.round((partPrice / total) * 10000) / 100;
    const kitPrice = reqPrice + partPrice;

    const finalKitName = kitName || `${reqComp.name} × ${partComp.name} Kit`;
    const today = new Date().toISOString().slice(0, 10);

    // BOB-generated IP & proprietary-protected pairing statement — LOCKED terms
    const ipStatement = [
      `KIT PAIRING AGREEMENT — IP & PROPRIETARY PROTECTION STATEMENT`,
      `Generated by BOB (BotOperatedBuilder) under the Magna Dev Yotta Protocol on ${today}.`,
      ``,
      `KIT: "${finalKitName}"`,
      `PARTY A (Requester): ${reqComp.builder_name || user.full_name} — Component "${reqComp.name}" (${reqComp.code})`,
      `PARTY B (Partner): ${partComp.builder_name || 'Builder'} — Component "${partComp.name}" (${partComp.code})`,
      ``,
      `1. IP OWNERSHIP — NO TRANSFER`,
      `   Each party retains full, exclusive ownership of all intellectual property in their own`,
      `   component, including source code, schemas, models, prompts, weights, and documentation.`,
      `   This pairing grants NO license, assignment, or transfer of IP between the parties.`,
      `   The kit is a co-marketing/co-distribution arrangement only.`,
      ``,
      `2. REVENUE SPLIT — PROPORTIONAL TO LIST PRICE`,
      `   Kit sale proceeds are split proportionally to each component's standalone list price:`,
      `   • Party A: ${requesterPct}%  (list $${reqPrice})`,
      `   • Party B: ${partnerPct}%  (list $${partPrice})`,
      `   Combined kit price: $${kitPrice}.`,
      ``,
      `3. NON-DISCLOSURE OF PROPRIETARY INTERNALS`,
      `   Neither party may access, reverse-engineer, reproduce, or disclose the other party's`,
      `   proprietary schema, architecture, prompts, or implementation internals. Each component`,
      `   operates as a sealed black box to the other. Breach terminates the kit immediately and`,
      `   may be reported under the Sensitive Intelligence Access & Reporting Policy.`,
      ``,
      `4. REVOCABILITY — EITHER PARTY, WITH NOTICE`,
      `   Either party may revoke this pairing at any time by giving 30 days' written notice via`,
      `   the platform. On the effective termination date the kit is delisted; standalone`,
      `   component sales and IP rights are unaffected. Sales completed before termination remain`,
      `   subject to the split above.`,
      ``,
      `5. INTEGRITY`,
      `   This statement is hashed (SHA-256) on generation. Any alteration after acceptance voids`,
      `   the agreement. Both parties must acknowledge these exact terms to activate the kit.`,
    ].join('\n');

    const ipStatementHash = await sha256(ipStatement);

    const pairing = await base44.asServiceRole.entities.KitPairing.create({
      kit_name: finalKitName,
      requester_id: user.id,
      requester_name: reqComp.builder_name || user.full_name,
      requester_component_id: requesterComponentId,
      requester_component_name: reqComp.name,
      requester_component_price: reqPrice,
      partner_id: partComp.builder_id,
      partner_name: partComp.builder_name || 'Builder',
      partner_component_id: partnerComponentId,
      partner_component_name: partComp.name,
      partner_component_price: partPrice,
      status: 'pending',
      ip_statement: ipStatement,
      ip_statement_hash: ipStatementHash,
      revenue_split: { requester_pct: requesterPct, partner_pct: partnerPct },
      requester_acknowledged: true,
      partner_acknowledged: false,
      kit_price: kitPrice,
      revoke_notice_days: 30,
    });

    return Response.json({ success: true, pairing });
  } catch (error) {
    console.error('createKitPairing error:', error);
    return Response.json({ error: error.message }, { status: 500 });
  }
});